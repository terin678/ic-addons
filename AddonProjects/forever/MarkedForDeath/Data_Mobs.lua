--[[
Data_Mobs: npc id to name per instance, for the rules editor's search, coverage and the
creature-type warning. Pure: no client call, ever.

Owned by lane E (data and capture). Everything between the GENERATED markers is rewritten
by scripts/mfd-forever-capture.lua when it merges capture exports; edit it by hand only in
the same format, one mob per line, ids ascending.

    Mobs.byInstance                 [instanceID] = { [npcID] = { name, boss, elite, creature } }

    Mobs.Get(npcID, instanceID, byInstance)   -> the entry, or nil
    Mobs.Name(npcID, instanceID, byInstance)  -> its name, or nil
    Mobs.ForInstance(instanceID, byInstance)  -> { { id, name, boss }, ... } bosses first, then by name
    Mobs.Find(name, byInstance)               -> { { id, instance }, ... } every exact (case-insensitive) match
    Mobs.Count(byInstance)                    -> mobs, instances

A missing mob only means search will not suggest it: a rule can always be typed by name,
so a gap is an inconvenience and a wrong entry is a lie. Inside instances a rule matches
by name, so the name here is the npc's own name as the client reports it.

Where the entries come from (ids and names as facts; no code or table layout copied):
  - bosses: ForeverDungeonJournal 1.6.6 (no licence stated, treated as all rights
    reserved). Where its display label differs from the npc's own name ("The Seven"),
    the npc name wins.
  - trash: QuestieDB 1.0.10 Forever build, npcs ranked elite, rare elite or boss whose
    zone is the dungeon's area (GPLv3 for new work, inherited content all rights
    reserved). The Forever-new dungeons carry almost no zone data there, so they list
    their bosses and little else until a capture fills them.
  - capture: /mfd capture in game, merged by scripts/mfd-forever-capture.lua.
]]

