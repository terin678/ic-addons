local function Lower(s)
    return type(s) == "string" and s:lower() or nil
end

function Mobs.Get(npcID, instanceID, byInstance)
    byInstance = byInstance or Mobs.byInstance
    if type(npcID) ~= "number" or type(instanceID) ~= "number" then return nil end
    local mobs = byInstance[instanceID]
    return mobs and mobs[npcID] or nil
end

function Mobs.Name(npcID, instanceID, byInstance)
    local entry = Mobs.Get(npcID, instanceID, byInstance)
    return entry and entry.name or nil
end

-- One instance's mobs as a list, bosses first, then by name, then by id.
function Mobs.ForInstance(instanceID, byInstance)
    byInstance = byInstance or Mobs.byInstance
    local list = {}
    local mobs = type(instanceID) == "number" and byInstance[instanceID]
    if not mobs then return list end
    for id, entry in pairs(mobs) do
        list[#list + 1] = { id = id, name = entry.name, boss = entry.boss == true }
    end
    table.sort(list, function(a, b)
        if a.boss ~= b.boss then return a.boss end
        if a.name ~= b.name then return a.name < b.name end
        return a.id < b.id
    end)
    return list
end

-- Every mob with exactly this name, ignoring case, by instance then id.
function Mobs.Find(name, byInstance)
    byInstance = byInstance or Mobs.byInstance
    local want = Lower(name)
    local hits = {}
    if not want or want == "" then return hits end
    for instanceID, mobs in pairs(byInstance) do
        for id, entry in pairs(mobs) do
            if Lower(entry.name) == want then hits[#hits + 1] = { id = id, instance = instanceID } end
        end
    end
    table.sort(hits, function(a, b)
        if a.instance ~= b.instance then return a.instance < b.instance end
        return a.id < b.id
    end)
    return hits
end

function Mobs.Count(byInstance)
    byInstance = byInstance or Mobs.byInstance
    local mobs, instances = 0, 0
    for _, list in pairs(byInstance) do
        instances = instances + 1
        for _ in pairs(list) do mobs = mobs + 1 end
    end
    return mobs, instances
end
